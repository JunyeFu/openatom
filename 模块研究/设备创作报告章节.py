"""作者到使用者的真实业务；时间图来自明确自建设计预期。"""
import json
from 业务设计报告章节 import gantt

def render_device_authoring(r,base,platform):
    cases={x['id']:x['manual_expected'] for x in json.loads((platform/'软件工程/scenarios/设备创作与采用/expected-authoring.design.json').read_text(encoding='utf-8'))['cases']}
    r.page('自定义设备：从素材到产线工作')
    r.p('一张图可以成为可配置设备的起点；但导入外观、定义作业、实例采用和公开贡献是不同决定。用户需要完成这整段工作，才能把设备放进可修改的工厂方案。','lead')
    r.table(['工作','用户决定与实际输出'],[
      ['新建/行为','选择仅外观或完整设备；明确输入、输出、资源和工时。'],
      ['素材/过程','选插图、序列或原生部件；定位端口，绑定实际阶段与标签。'],
      ['隔离试用','示例物品/资源和接收条件；外观预览与行为运行分别显示。'],
      ['本地保存','保留草稿或指定版本设备定义；保存不自动发布。'],
      ['工程采用','实例选择位置、物品/资源映射和公开参数；不导入另一份库存。'],
      ['改版/交接','显示受影响实例和连接，再明确采用；允许带出的资产随包交付。']], [.25,.75])
    r.p('纯外观仍可用于布局讨论，但不计成有产能设备。缺照片可明确换内置图标；缺作业或必要连接不能从画面补出能力。八个变体仅是设计预期，编辑器尚未实现。')

    r.page('设备定义与实例：库中修改不偷偷生效')
    r.table(['对象','保存/消费内容'],[
      ['设备定义','模块id/version、端口、行为、公开参数、表现和示例。'],
      ['工程实例','独立id、指定定义版本、位置、参数覆盖、库位/资源连接。'],
      ['方案','完整配置和输入，运行中修改进入下一方案草稿。'],
      ['执行结果','实际执行的方案，不能自动改归最新库版本。']], [.27,.73])
    r.p('同一个包放两台设备，会有两个独立实例；人员、库位和正式库存仍由工程提供。资源角色未绑定时是缺项，不能自动新增一名工人。实例只能覆盖定义公开的参数。')
    r.p('改实例不修改库或其他实例。另存模块后，选择要升级的实例，列端口/参数/布局/表现差异；取消保留旧方案。版本号不是兼容证明，名称相似不是物品类型匹配。')

    r.page('图片时间轴：两种绑定，各有工时含义')
    r.table(['方式','有效规则'],[
      ['单阶段固定周期','全周期u与唯一工时；片段重排只改变表现。'],
      ['多阶段作业','绑定实际phase_id及阶段有效进度；阶段内排序。'],
      ['跨阶段拖图片','明确重新绑定表现，不自动重排工序或资源。'],
      ['修改工时','固定周期同比调整片段；多阶段只改明示可缩放值。'],
      ['等待/人工确认','不计有效加工，未知时不造整体剩余秒数。']], [.29,.71])
    r.table(['表现片段','60秒周期','只改为30秒'],[
      ['A：0.2','12秒','6秒'],['B：0.35','21秒','10.5秒'],
      ['C：0.3','18秒','9秒'],['D：0.15','9秒','4.5秒']], [.38,.31,.31])
    r.p('自建输入2壳体/1PCB/1人，两种工时都只能形成1件。重排未绑定生产阶段的图片不改变这个配比；此例没有把四张图当四次加工。','small')

    r.page('时间图：有效60秒，交接却在85秒')
    c=cases['phase_wait_and_output_hold']
    rows=[dict(kind=x['phase'],item='part-1',start_ms=x['start_ms'],end_ms=x['end_ms'],resources=['CNC']+(['W-C'] if x['phase'] in ['load','unload'] else [])) for x in c['intervals']]
    rows += [dict(kind='wait_for_worker' if w['reason']=='phase_resource' else 'wait_for_output',item='part-1',start_ms=w['start_ms'],end_ms=w['end_ms'],resources=['CNC']) for w in c['waits']]
    rows.append(dict(kind='其他工作',item='another-job',start_ms=50000,end_ms=70000,resources=['W-C']))
    gantt(r,rows,['CNC','W-C'],90,'横轴秒。自建示例：设备全程持有；人员只上下料占用，另有50—70秒工作。')
    r.table(['事实','时长/时点'],[
      ['上料/自动/下料','10＋45＋5＝60秒有效加工'],
      ['自动结束，等下料员','55—70秒保持自动段结束姿态'],
      ['做完但接收位置满','75—85秒仍在设备，保持完成姿态'],
      ['接受后释放设备','85秒才入输出库位、设备再次可用']], [.49,.51])
    r.p('这张图说明生产状态怎样驱动画面，不能用动画播放结束代替物料交接；示例不对应真实设备节拍或企业收益。')

    r.page('等待的四种画面：物品不能凭空转移')
    r.table(['情形','画面','物品与状态'],[
      ['未开工缺料','空闲/开工前姿态','没有当前在制；显示缺项。'],
      ['阶段边界等人','上一阶段终姿态','设备和在制保持；下一阶段尚未开始。'],
      ['加工中服务中断','冻结中断姿态','按pause_resume或abort处理，不自动可恢复。'],
      ['做完等待接收','完成姿态＋待移交','结果仍在设备，接收前不是输出库存。']], [.28,.32,.40])
    r.table(['例中时点','必须呈现的状态'],[
      ['60秒','等下料；保持auto_end，输出接收0。'],
      ['72秒','下料阶段有效进度40%，物品仍在设备。'],
      ['80秒','加工做完、待移交，输出接收仍0。'],
      ['85秒','输出库位接受1件，设备释放。']], [.24,.76])
    r.p('装配样例的waiting/open仅用于未开工，不能照搬到阶段等待。暂停、回看、观看循环或三档画布显示都不能改变持有者。')

    r.page('版本采用：只升级A，B和旧方案保留')
    a=cases['selected_visual_upgrade'];b=cases['selected_behavior_upgrade']
    r.table(['决定','A实例','B实例','结果责任'],[
      ['原定义','0.1.0 / 60秒','0.1.0 / 60秒','原结果属于原方案。'],
      ['仅采用新外观',a['versions_after']['A']+' / 60秒',a['versions_after']['B']+' / 60秒','展示新表现不等于新运行成功。'],
      ['采用工时变更',b['versions_after']['A']+' / 30秒',b['versions_after']['B']+' / 60秒','新输入重新彩排。'],
      ['pcb→pcb_v2','原连接/标签待重绑','保持原定义','不自动按名称重接。']], [.24,.22,.22,.32])
    r.p('显示文字改名且稳定ID不变，连接仍成立；删除/改型端口则列真正受影响关系。允许存待补草稿；未采用时保持旧实例。占地或路径端点变化还需核对布局与运输规则，不能当作纯外观。')
    r.p('上述版本是自行设计输入，当前没有执行模块升级。没有引入在线版本服务；库中定义、实例采用和工程交付继续使用既有目录。','small')

    r.page('标签、操作与交接：信息对应真实对象')
    r.table(['入口','业务含义'],[
      ['port.available','选中实例绑定库位的物品/单位/可用量，不是全厂同名总量。'],
      ['active_item','当前工序物品；空闲时无当前物品，不留上件读数。'],
      ['configure','修改草稿；运行查看中打开下一方案。'],
      ['inspect','看端口、状态、持有者与缺项。'],
      ['preview_cycle','引擎实现后执行隔离示例，不用正式库存。']], [.28,.72])
    r.p('例中80秒“工序做完1、已移交0”，85秒才是1/1；这两个读数不再生成库存，也不代表合格或客户接受。删端口/参数会列依赖标签与连接；没有对应行为的夹紧/点动仍未支持，Agent使用同样能力。')
    r.p('交接/公开按资产决定附带、引用或明确替换。八变体的假设允许自建几何再分发，私人照片及行业原文不附公开包。它是许可流程示例，不证明已有实际素材授权。')

    r.page('创作贡献与实现：主文件已同步')
    r.table(['任务/消费者','要实际交付的能力'],[
      ['P3-01 / module-kit','可编辑定义、真实实例绑定、显式采用、导入和交接。'],
      ['P1-03 / simulation','真实阶段、资源等待、物品持有和有效进度。'],
      ['P3-02/03 / presentation','各素材按阶段进度显示，等待姿态与标签一致。'],
      ['P3-04 / Agent','生成草稿、实际渲染反馈、人工编辑与明确采用。'],
      ['贡献者与维护者','同包重开修改；外观和行为变化分别说明，素材许可逐项填写。']], [.31,.69])
    r.p('八个预期已复算片段比例、等人/待移交、资源区间、版本作用范围和声明交接。产品任务保持planned；没有编辑器实测、模块发布或现场验证。')
    r.p('规则直接写入设备规格、Agent契约、模块与贡献说明、实例样例和任务依赖。不是另写一份以后无人采用的备注；完整研究专业范围仍沿用后续41份模块说明。')
