"""投用/服务/专业接入的连续业务；图使用明确预期，完整专业任务仍沿用原定义。"""
import json,html
from collections import Counter
from 业务设计报告章节 import gantt

D=86400000
def render_readiness_and_professional(r,base,platform):
    cases={c['id']:c for c in json.loads((platform/'软件工程/scenarios/投用与专业接入/expected-readiness.design.json').read_text(encoding='utf-8'))['cases']}
    r.page('何时能生产：建设、投用与专业条件')
    r.p('安装好了不等于目标已可用于生产；认可图纸也不等于完成联调。方案要把建设任务、专业成果、服务容量和投用决定接到后续作业，才能解释真正的开始和交付时点。','lead')
    r.table(['决定','后续实际消费什么'],[
      ['场地/厂房','认可位置、建设任务与目标投用条件。'],
      ['设备/控制柜','安装/接线/软件配置、所用成果版本和受支持联调。'],
      ['工艺/工装','产品版本、工具/板位、认可作业、首件前置。'],
      ['公用服务','在对应阶段满足电/气/水/冷容量、单位与声明品质。'],
      ['投用','明确在何时、什么范围内可用，来源是预设还是实际证据。']], [.28,.72])
    r.p('本章设计以九个自建变体核对；没有现场验收，也未运行专业程序。两画布保持，投用与服务在对象详情、覆盖层和共同时间轴中设置。')

    r.page('建设支线：并行准备到同一投用条件')
    r.table(['任务/对象','输入与前置','输出及人工决定'],[
      ['机械安装','设备到货、位置及认可条件','安装任务完成，不自动开启生产。'],
      ['柜体/接线','认可连接与柜体、到货和安装','准备好的设备条件，不是每件产品的工序。'],
      ['联调/准备','机械与电气前置、程序/服务范围','模拟或实际范围明确的结果。'],
      ['目标投用','所有必要条件与采用决定','给设备/线组/厂房开放指定能力。']], [.24,.36,.40])
    r.p('任务之间可串并联；人员/施工日历如果未知，只显示计划跨度，不从三天安装推导72小时人工。改造选择并行安装、停机窗口或替换，并明确旧设备/在制是否继续服务。')
    r.p('图纸、成果认可、安装完成、联调结果、投用各有独立含义。日期到达不产生合格决定；没有建设包的旧样例沿用其明确初始可用假设。')

    r.page('建设时间图：生产窗口没有跟着延期')
    labels={'mechanical':'机械安装','cabinet':'柜体到货','wiring':'接线','trial':'联调'}
    for key,title in [('commission_cabinet_d2_h24','基线：D3 12:00模拟投用'),('commission_cabinet_d5_h24','柜体延期：D6 12:00模拟投用')]:
        r.heading(title)
        rows=[dict(kind='计划',item=j['id'],start_ms=j['start_ms'],end_ms=j['end_ms'],resources=[labels[j['id']]]) for j in cases[key]['project_tasks']]
        gantt(r,rows,list(labels.values()),8,'横轴为建设日D；条带为计划日历跨度，不是施工人员连续占用。',D)
    r.p('生产共同起点D4 08:00。基线投用早20小时；延期投用晚52小时。原24小时窗：基线2件70分钟完成，延期0件、完整时刻为空。扩至72小时仍同起点，延期53小时10分完成。','small')

    r.page('公用服务：量和品质各有边界')
    r.table(['服务量','必要区分'],[
      ['电：kW或kVA','有功/视在容量不自动混算；背景与阶段增量分开。'],
      ['气：流率','参考温压、表压/绝压类型与品质明确；额定流量不推导末端压力。'],
      ['冷/热：kW或流率','工况和供回边界，热图不代表可供应能力。'],
      ['水：流率及专业品质','来源/排出和组分范围；不按零件数量处理。']], [.34,.66])
    r.p('服务绑定关联设备/阶段、源和连接点，仍属于resources/professional。三类物品/信号/成果端口继续使用，服务不生成库存，也不创建另一张常态画布。')
    r.p('对同单位/参考条件的源v：背景B_v(t)＋各阶段增量Σd_j,v(t)≤容量C_v(t)。共享上级与分支都要满足，不能给两个厂房各复制一份公共供电。未建模服务不被宣传为充足。')

    r.page('容量案例：单独扩电或扩气都不够')
    r.table(['供电/供气','作业安排','2件完成'],[
      ['10kW / 3L/s','顺序执行','60秒'],['14kW / 3L/s','仍受气限制','60秒'],
      ['10kW / 5L/s','仍受电限制','60秒'],['14kW / 5L/s','两台并行','30秒']], [.34,.40,.26])
    for key,title in [('utility_base','基线顺序'),('utility_both','同时提高两项声明容量')]:
        r.heading(title); c=cases[key]
        rows=[dict(kind='auto',item=i['machine'],start_ms=i['start_ms'],end_ms=i['end_ms'],resources=[i['machine']]) for i in c['intervals']]
        gantt(r,rows,['M1','M2'],60,'横轴秒；每机30秒、6kW、2L/s，设备和人员已可用。')
    r.p('所有数值是自建声明。同一负载总能量0.1kWh、气量120L，顺序和并行都相同；更快不自动节能，扩容投资/费用未知。没有压力、电网或真实工艺求解。','small')

    r.page('服务中断：不能继续按原速产出')
    c=cases['utility_outage_pause_resume']
    rows=[dict(kind='auto' if i['state']=='active' else 'wait_for_supply',item=i['machine'],start_ms=i['start_ms'],end_ms=i['end_ms'],resources=[i['machine']]) for i in c['intervals']]
    gantt(r,rows,['M1','M2'],90,'40—70秒供电容量为0。该工序明确允许pause_resume；机器/物品保持，服务释放。')
    r.table(['时点','业务状态'],[
      ['30秒','第1件完成，第2件开始。'],['40秒','第2件做了10秒；停有效进度，保留在制。'],
      ['70秒','服务恢复，重新取得全部阶段条件。'],['90秒','再做剩余20秒，第2件才完成。']], [.23,.77])
    r.p('不可恢复的工艺必须有隔离/中断处置；没有规则不自动选暂停继续。图是有限预期，没有真实供电中断或设备控制。背景与等待用量本例为0，实际场景需明确配置。')

    r.page('专业成果：四个对象各自负责')
    r.table(['对象','责任'],[
      ['artifact','产品/工艺/设备版本、输入条件、单位/坐标、内容与支持范围。'],
      ['acceptance','人决定成果可用于哪个对象和用途，附条件与来源。'],
      ['consumer_binding','指定目标/工序实际需要哪些字段与版本。'],
      ['execution_result','实际工具/软件目标、输入输出、状态和失败/未支持原因。']], [.31,.69])
    r.p('同一r1成果仍能用于原r1订单；新r2使不匹配绑定需要复核，不全局删除旧成果。声明过程、实际名义计算和软件在环明确选择；请求计算结果却只给工时不能静默降级。')
    r.p('已安装软件、已导入文件、已有漂亮画面都不等于完成相应专业执行。手算预期只放expected，生产结果与专业producer_result保持真实。')

    r.page('专业接口例：版本、单位与范围')
    r.table(['条件','有限预期'],[
      ['r1：100×60×30；旧盒104×64×34mm','每侧2mm间隙，固定姿态：包络满足。'],
      ['r2：108×60×30；继续用旧盒','包络不满足；旧r1绑定也不匹配。'],
      ['r2：新盒112×64×34mm','包络满足，只说明这个检查子集。'],
      ['需要名义NC但无实际结果','不接受缺失结果，不能由工时推导。'],
      ['程序超支持方言 / 气量参考不一致','未支持/需复核，不强制执行或直接相加。']], [.49,.51])
    r.p('矩形算术用于核对接口，不是完整纸包装、折叠、取物、强度或制造层求解。认可用途必须写清；“这个尺寸条件成立”不能变成所有专业条件通过。')

    r.page('完整纸包装任务：原专业深度继续保留')
    r.table(['专业步骤','实际交给下一步的内容'],[
      ['功能要求与产品','包络、用途、姿态、材料和连接条件。'],
      ['结构与过程','板片/折带/固定连接、多件结构、成型/开合/声明取物序列。'],
      ['条件检查与取舍','硬几何条件及失败位置；同量纲事实比较，不造综合分。'],
      ['认可与制造','认可过程、刀/折/胶层及可编辑工程。'],
      ['实际装盒与交付','当前产品/包材、动作、人员和数量；身份、库存与接受。']], [.30,.70])
    r.p('本轮接口例不缩减完整专业目标。几何容纳也不能自动给出装盒工时、包装机程序或材料防护质量。未来接入数控名义几何和装配条件时，产品输入来自实际成果，变更影响需继续传到包装。')

    r.page('软件在环：程序实际做了什么')
    r.table(['调用','时间/物品责任'],[
      ['离线求解','彩排前产生成果；计算墙钟不当生产加工时间。'],
      ['受支持软件步进','按工厂边界事件或认可步长反馈；内部求解方式保留。'],
      ['模型推理','真实会话输入输出，判据/放行另由规则消费，不直接加库存。'],
      ['控制请求','request→前置/占用→accepted/waiting→完成反馈；接受不等于产出。']], [.29,.71])
    r.p('软件目标、版本、输入/输出与支持范围明确。首版仅隔离软件对象；没有目标适配时标未支持，不说已接真机。只有工厂引擎提交物料变化，专业工具不会成为第二库存或第二生产时钟。')
    r.p('公开近邻已能在虚拟环境运行控制逻辑。完整工作链与开放工程接手仍需实际对比，本项目不能以“也能联调”直接认定首创。','small')

    r.page('41个专业方向：消费者已逐项对齐')
    integration=json.loads((base/'专业接入目录.json').read_text(encoding='utf-8'))['modules']
    counts=Counter(m['category'] for m in integration)
    r.table(['研究分组','条目','接入责任'],[[cat.split('_',1)[1],n,'保留原定义，成果/条件进入指定准备、投用、运行或分析消费者。'] for cat,n in counts.items()],[.34,.12,.54])
    r.p('每份模块说明和JSON/CSV/SQLite同步工程角色、成果类型、最低业务字段及实际消费者。后面的逐模块章节已直接增加这些内容；独立目录不是运行插件清单。')
    r.p('建设、环境和公用工程旁接目标条件；过程研发/连续材料方向保留新增类型范围，不能强行成为每件产品必经工位。全部提供者当前planned，首版实际能力以选定并实现的范围记录。')

    r.page('实施与交付：规则进入已有目录')
    r.table(['任务','要形成的完整成果'],[
      ['P0-03','共同日历、投用/服务与专业成果绑定。'],
      ['P1-06','投用前置及同起点/观察窗。'],
      ['P1-07','共享容量、阶段取得、降容与中断处置。'],
      ['P2-07','两画布中的投用/服务面板、等待与范围。'],
      ['P4-02','完整纸包装专业输出真正接到后续作业。'],
      ['P4-03','隔离软件目标的实际程序/工具反馈。']], [.24,.76])
    r.p('九变体已复算日历、投用、容量、能量、程序/包络范围；产品任务仍planned。原专业范围与模块定义保留，没有以小算术代替实际专业实现。')
    r.p('接手包保存共同时间参考、所用专业版本与认可、投用/服务配置、已知缺项和实际结果。模型/后置/厂家资产等按所用文件许可处理，原始下载资料不自动公开捆绑。')

    r.page('本轮原始依据与未取得范围')
    source=json.loads((platform/'研究资料/投用与专业来源.json').read_text(encoding='utf-8'))
    for s in source['sources']:
        r.heading(s['id']+' '+s['title'])
        r.p(s['reading_location'],'small')
        r.p('<link href="'+html.escape(s['url'],quote=True)+'" color="#126679">原始来源</link>　'+html.escape(s['limits']),'small',True)
    r.p('取得4份原页并核对相应正文；DOE仅检索线索可见，入口/历史手册未取得，不使用其具体缓存数据。既有FreeCAD/ONNX等资料继续保留，不重复计为新专业成果。','small')
