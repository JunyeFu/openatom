"""独立模板与工程接手；图表只用已标注有限声明预期。"""
import json
from 业务设计报告章节 import gantt

def render_template_handoff(r,base,platform):
    d=json.loads((platform/'软件工程/scenarios/模板与交接/expected-template-handoff.design.json').read_text(encoding='utf-8'))
    cases={c['id']:c['manual_expected'] for c in d['cases']}
    r.page('三类工厂：独立工程，共同模块')
    r.p('模板不只是一段范围描述。三份独立设计现在各有产品/物品、库位、设备、角色、阶段、端口、种子供给与专业要求，并引用同一模块库。','lead')
    r.table(['模板','完整任务'],[
      ['机加工检验与包装交付','毛坯、受限加工、检验、装盒和声明成品库位接受。'],
      ['外购件齐套总装与包装','壳体/PCB/螺钉齐套、总装、检查处置和箱件关系。'],
      ['机电支线并行制造与总装','外壳与板件支线、准备/阶段、后续处理、齐套与检验包装。']], [.40,.60])
    r.p('各模板有manifest和project.design.json，依然是设计而非运行插件。电子专业保留完整原任务输入；采购完成PCB是替代路线，不能计为自产贴装已执行。')
    r.p('两张常态画布、三档流水线显示和单击详情保持。旧规格中的四主视图及原课题代号已直接修正；专业工作台与经历/时间轴在详情或面板中。','small')

    r.page('端口和配方：修正真正的引用不一致')
    r.table(['设计缺口','当前直接修正'],[
      ['旧装配定义只有壳体/PCB','新三输入定义增加4螺钉，原两输入样例保持。'],
      ['加工件需要装盒，但旧盒只接装配体','通用检验/包装用公开product_item参数匹配。'],
      ['released_assembly被当物品名','实际物品仍assembly，released是质量条件。'],
      ['检验结果文字被当端口','连接用真实passed/rework端口，PASS/FAIL仍是结果。'],
      ['模块默认工时与实例声明不同','先应用公开参数，再解析端口与工时；资源角色映射同一人员。']], [.42,.58])
    r.p('三模板按实际引用文件核对id/version、公开参数、端口/库位类型、单位、资源和阶段；从零案例的原440/570秒预期保持。这个检查不替代实际加载器或生产运行。')
    r.p('新定义使用本项目自建原生几何，尺寸为表现假设。原生数据可编辑不表示已实现设备编辑器或具备真实机床参数。','small')

    r.page('三模板名义预期：相同规则，不同输入')
    r.table(['声明案例','种子物料','两件包装接受'],[
      ['机加工','2毛坯、2盒','90 / 150秒'],
      ['外购总装','2壳体、2PCB、8螺钉、2盒','70 / 110秒'],
      ['并行制造','2毛坯、2裸板、16部件、8螺钉、2盒','160 / 200秒'],
      ['并行制造，仅板件准备30改90秒','其他相同','220 / 260秒']], [.30,.43,.27])
    r.p('全部观察0-300秒、工位间瞬时移交、检验预设PASS。机械60秒，板件每板30秒及声明后续30秒，装配40、检验10、包装20；准备仅做一次。')
    r.p('这些是有限数量/时序推导，不是工业吞吐、实际专业加工或客户履约。几何、焊接、电气质量与软件运行都没有在这些结果中得到验证。')
    r.p('板件样例保留实际元件库/原生Job/受支持机器等缺项。切到专业模式后必须取得真实提供者和结果，不以声明时长降级冒充计算。','small')

    r.page('准备改变怎样传到全厂时间轴')
    names={'setup':'板件准备','board_load':'上板','board_place':'声明组装','board_unload':'下板','board_finish':'后续处理'}
    for key,title in [('parallel_manufacturing','30秒一次准备'),('parallel_board_preparation_90s','90秒一次准备')]:
        r.heading(title)
        jobs=[dict(j,kind=names.get(j['kind'],j['kind'])) for j in cases[key]['jobs']]
        gantt(r,jobs,['CNC01','Board01','BoardFinish01','Assembly01','W-B'],300,
              '横轴秒，共同输入和窗口；展示设备及检验/包装共用人员，完整人员轨在源预期。',
              palette_overrides={'板件准备':'#866bb2','后续处理':'#54869b'})
    r.p('板件准备不改变CNC工时，却推迟汇合、总装与包装；图只说明声明规则的连接，不证明板件实际贴装/后续工艺。','small')

    r.page('实例化：复制布局，不复制现有物品')
    r.table(['动作','处理'],[
      ['新工程选模板','列演示供给/需求，用户明确采用种子数据。'],
      ['插入已有工程','默认加入布局/定义，库存/订单新增0；带入批次另作选择。'],
      ['复制设备/线组','新对象ID并重写内部引用，原在制不复制。'],
      ['同名物品','按ID/单位/规格明确匹配，不按显示名字合并。'],
      ['采用资源','角色映射已有工程人员，同一身份取得一次。'],
      ['对外连接','保留待接入项；不能接到错误物品/版本。']], [.29,.71])
    r.p('模组定义版本共享，实例位置/参数独立。库位和设备复制不等于又有2件库存或多一张订单；模板只是组合入口，不创建第二引擎、时钟或账本。')

    r.page('交接打开：缺项有不同影响')
    r.table(['情况','接手者能做什么'],[
      ['包内版本与本机最新版不同','使用工程明确引用的包内文件；不覆盖全局库或自动升级。'],
      ['缺照片/模型','保留待补或明确用内置表现替换，行为不变。'],
      ['缺必需定义/端口/资源','继续编辑布局，相关作业不可执行，整厂结果不完整。'],
      ['缺所请求专业结果','等待受支持提供者；改声明模式必须明确新建方案。'],
      ['只有设计包/旧结果','未运行留空；旧结果仍属旧输入，不能冒充新结果。']], [.42,.58])
    r.p('导出所用模块和允许附带素材，重写包内相对路径；不以作者绝对路径当另一人可打开的依赖。未授权资产、缓存、凭据与下载行业原文不自动附带。')
    r.p('实际软件第三人重开、修改、运行、再交回才证明接手能力；读JSON仅证明设计文件可携带和解析。','small')

    r.page('从中间继续：保持时间、物品和需求基数')
    r.table(['T=60秒的声明状态','正确的继续'],[
      ['原作业有效20/40秒','剩余20秒，到80秒完成，不重新领料/从头做40秒。'],
      ['物品在车辆等待接收','75秒接受前保持车辆持有，不恢复来源库存。'],
      ['未来90秒到料','保留原事件时点，过去事件不再重放。'],
      ['原需求4、已接受2','新增2、累计4，分清基数与增量，不再生产已接受基数。'],
      ['专业状态不能保存/恢复','可阅读或从头新跑，不能静默重启半个Job。']], [.47,.53])
    r.p('只有完整实际快照才可续做：含物品/容器、质量/分配、在制进度、资源/车辆、未来事件、需求与所用版本/专业状态。截图或部分表格不够。')
    r.p('当前没有真实快照；这一例核对必要状态和期望，actual_resume_result仍为空。普通方案比较继续从共同起点重跑。','small')

    r.page('社区参与：从有用提案到可采用版本')
    r.table(['状态/角色','要交什么'],[
      ['设计提案','完整任务、输入输出、预期、支持范围和许可缺项。'],
      ['可编辑示例','真正文件和重开说明；运行证据另列。'],
      ['运行候选/可发布','实际输入、版本和输出；复现、作者、维护与许可。'],
      ['素材/标签/模板作者','可独立改一个资产，不要求重写整个专业系统。'],
      ['核心/模块维护者','真实确认后认领；行为/接口变化说明消费者影响。'],
      ['暂停维护','保留最后适用版本，旧工程不自动升级或删除。']], [.35,.65])
    r.p('28项实现任务仍planned；P2-03落实软件接手，P4-01落实模板，P5-01落实真实第三人演练与发布。社区人数、组织支持与响应承诺不编造。')
    r.p('代码拟Apache-2.0，实际发布核对依赖；素材/模型分别授权。当前仅设计和文件检查，不自动向外提交PR或发布。','small')
