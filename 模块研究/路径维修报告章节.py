"""路径与维护的完整工作链；所有图表只使用自建有限预期。"""
import json
from 业务设计报告章节 import gantt

def render_logistics_maintenance(r,base,platform):
    data=json.loads((platform/'软件工程/scenarios/路径与维修/expected-logistics-maintenance.design.json').read_text(encoding='utf-8'))
    cases={c['id']:c['manual_expected'] for c in data['cases']}
    r.page('布局移动：坐标也进入物流计算')
    r.p('整线移动保留内部关系，却改变实际规划布局。新的厂房坐标要同时供画布、包络和认可路径使用；若只改显示位置，运输分析仍会使用旧距离。','lead')
    r.table(['设置','输入与结果责任'],[
      ['固定时间','保留装卸、去返程声明值；移动后注明未重估，不自动宣称更快。'],
      ['认可路径','有向节点/边、接入点、米制长度和速度；不穿墙补直线。'],
      ['共享约束','道路/冲突区、车辆等待位置、角色和日历是明确条件。'],
      ['跨厂连线','默认概念供应；卡片屏幕距离不是公里或运输时间。']], [.28,.72])
    r.p('路线找不到合法连接则待重接；只有已实现工具的真正输出才能采用。逻辑容量不证明实际交通净空、防撞或车辆运动学。常态画布仍只有流水线和多厂房。')

    r.page('车辆位置：先空驶，再装载和交付')
    r.table(['阶段','车辆与物品'],[
      ['前往取货','车辆从当前位置空驶；来源物品可被预留但未离库。'],
      ['装载/发出','发出才从来源转为车辆持有，不在两处重复出现。'],
      ['在途/抵达','按认可连接和共享占用移动；抵达不等于目的接受。'],
      ['等待/卸载','保持货物，取得接收条件；卸载完成才提交一次移交。'],
      ['返程/下一位置','空车仍有路径与资源条件；可按声明留目的地，但不瞬移到新取货点。']], [.28,.72])
    r.table(['自建变体','库位接受','车辆可再用'],[
      ['10m路径 / 1m/s','15秒','25秒'],
      ['移动后20m认可路径','25秒','45秒'],
      ['先空驶5m，再走10m','20秒','30秒'],
      ['移动但仍固定时间模式','15秒','25秒，时间未重估']], [.50,.25,.25])
    r.p('各例2秒装载、3秒卸载；产出指声明库位接受，不推导客户收货或年产能。速度与工时为自行设计输入。','small')

    def road_rows(c):
        rows=[]; colors={}
        for j in c['corridor_occupation']:
            vehicle=j['vehicle']; kind=vehicle+('载货' if j['kind']=='loaded' else '空返')
            colors[kind]=('#126679' if vehicle=='A' else '#427795') if j['kind']=='loaded' else '#98aab4'
            rows.append(dict(kind=kind,item=vehicle,start_ms=j['start_ms'],end_ms=j['travel_arrival_ms'],resources=['共享区']))
            if j['end_ms']>j['travel_arrival_ms']:
                wait=next((w for w in c['destination_waits'] if w['vehicle']==vehicle),None)
                unload_start=wait['end_ms'] if wait else j['travel_arrival_ms']
                if unload_start>j['travel_arrival_ms']:
                    rows.append(dict(kind='wait_for_output',item=vehicle,start_ms=j['travel_arrival_ms'],end_ms=unload_start,resources=['共享区']))
                rows.append(dict(kind='unload',item=vehicle,start_ms=unload_start,end_ms=j['end_ms'],resources=['共享区']))
        return rows,colors

    r.page('共享通道：空车也不能穿过另一辆车')
    c=cases['opposing_base'];rows,colors=road_rows(c)
    gantt(r,rows,['共享区'],54,'横轴秒；8m双向容量1通道，A/B在2秒就绪，按就绪时间及ID。',palette_overrides=colors)
    r.table(['任务','通道占用','目的接受/返回'],[
      ['A载货','2-10秒','13秒接受'],
      ['B载货','10-18秒','21秒接受'],
      ['A空返','18-26秒','26秒返回'],
      ['B空返','26-34秒','34秒返回']], [.25,.36,.39])
    r.p('两个方向共享同一资源，不能复制一条路各供一辆车。进入下一段前取得冲突区和安全退出位置；明确等待点与容量，离开才按规则释放。')
    r.p('多边、多区按认可路线和声明条件组合；当前自建图只核对一个冲突区的完整去返程，不冒充通用交通引擎。')

    r.page('候车位：同样接收条件，不同后车等待')
    for key,title in [('blocked_with_outside_bay','有通道外候车/装卸位'),('blocked_without_outside_bay','两端均无通道外位')]:
        r.heading(title);c=cases[key];rows,colors=road_rows(c)
        gantt(r,rows,['共享区'],54,'相同横轴秒；A目的空间20秒才可用。区外位与库位容量分别设置。',palette_overrides=colors)
    r.table(['位置安排','A/B库位接受','A/B返回'],[
      ['区外位置','23 / 21秒','37 / 29秒'],
      ['两端无区外位置','23 / 34秒','42 / 50秒']], [.42,.29,.29])
    r.p('区外位让A保持货物却释放通道。没有区外卸载位时，等待和卸载都占路，连B的卸载3秒也要计入。该差异来自明确布局/释放规则，不来自更快速度或增车。','small')

    r.page('不可达与循环等待：保留实际条件')
    r.table(['情形','画面/解释','不可暗做什么'],[
      ['删除认可路径Q→R','待重接，货物仍在来源；接受时刻为空。','不改成穿墙直线或0秒运输。'],
      ['A持P1等P2，B持P2等P1','显示持有者、请求位置与无后续释放事件。','不复制位置、车辆或货物，不自动声称有最优解。'],
      ['目的满但有区外位','车辆在该位置持货，通道可释放。','不把物品提前画进目的库存。'],
      ['临时取消/改派','未发出释放预留；在途要明确目的或退回任务。','不把在途货物瞬间恢复来源。']], [.28,.43,.29])
    r.p('用户修改候车容量、方向、接入段或派工后，从共同起点重新彩排。路径失效与资源占用是不同问题；视觉箭头相交不自动意味着物理碰撞区。')

    r.page('维护不是复位：物品和恢复条件继续存在')
    r.table(['停法','当前作业与后续条件'],[
      ['finish_current','阻止新单，当前作业到认可停机点；输出满也可能推迟维修。'],
      ['pause_resume','明确允许保留/续做，冻结有效进度；维修、复核、决定后续剩余工作。'],
      ['abort_disposition','终止尝试，合法转待判/隔离；材料不自动退回，缺口不自动补产。'],
      ['策略未知','待处置，不默认选择方便的恢复。']], [.30,.70])
    r.p('原作业保存resume_ref及物品，当前设备使用权按生产→维修→复核→恢复交接。恢复关联不重复计机床容量，等备件时设备不可生产但维修人尚未工作。')
    r.p('备件是消耗物品，工具是复用资源。维修完成不等于投用/专业范围/服务与质量条件均满足；整厂复位是重放初始方案，不是修复后的继续生产。')

    r.page('维修时间图：等备件不算维修人工')
    c=cases['maintenance_pause_resume']
    names={'production':'加工','waiting_for_maintenance_inputs':'等维修条件','repair':'维修','qualification':'复核','production_resume':'续做'}
    rows=[dict(kind=names[j['kind']],item='first',start_ms=j['start_ms'],end_ms=j['end_ms'],resources=['设备状态']) for j in c['intervals']]
    rows.append(dict(kind='维修',item='repair-worker',start_ms=c['repair_start_ms'],end_ms=c['repair_end_ms'],resources=['维修人员']))
    gantt(r,rows,['设备状态','维修人员'],120,'横轴秒；原作业0-30后暂停，维修人40可用、备件50到；复核为声明预设。',palette_overrides={'等维修条件':'#b57939','维修':'#866bb2','复核':'#9f9057'})
    r.table(['区间','有效工作/持有'],[
      ['30-50','设备不可生产，原在制保留，维修人未工作。'],
      ['50-70','维修排他使用设备并消耗备件；维修人工20秒。'],
      ['70-80','复核，没有恢复合格生产。'],
      ['80-110','原物品续剩余30秒，合计有效加工60秒。']], [.27,.73])
    r.p('设备状态轨显示不可用跨度，不把每段都当有效资源工作。维修人轨只显示真实声明维修阶段；本例自动加工/预设复核不额外推导生产或检验人工。','small')

    r.page('完成当前再停：待移交也影响维修')
    c=cases['maintenance_finish_current']
    names={'production':'加工','output_wait':'等接收','repair':'维修','qualification':'复核','production_second':'下一件'}
    rows=[dict(kind=names[j['kind']],item='job',start_ms=j['start_ms'],end_ms=j['end_ms'],resources=['设备状态']) for j in c['intervals']]
    gantt(r,rows,['设备状态'],180,'横轴秒；30秒停新单，首件60秒做完、80秒才接受；维修和复核之后才接下一件。',palette_overrides={'等接收':'#b57939','维修':'#866bb2','复核':'#9f9057'})
    r.p('维修80-100秒，复核100-110秒，第二件110-170秒。若只看加工完成60秒，便会错误地把60-80秒同时算成维修和物品待移交占用。')
    r.table(['另一种预定规则','结果'],[
      ['已知硬停30-80秒、60秒阶段不可中断','0-30秒不够连续执行，不开工；80-140秒完成。'],
      ['日历只有不可用窗口','不能据此编造维修人工、备件消耗或复核结果。']], [.51,.49])
    r.p('两种安排由用户选定的停法与工艺条件决定，不能拿更方便的那一种当所有机器通用恢复方式。')

    r.page('处置与复核失败：未完成保持未完成')
    r.table(['变体','在制/结果','数量与时点'],[
      ['终止并移交隔离','30-35秒移交原物品，身份/组成保留、质量pending。','原材料不退回；原计划第二件80-140秒，完成1件。'],
      ['复核FAIL','原作业有效30秒保留，等待放行。','完成时刻为空；不自动继续。'],
      ['中断策略缺失','原物品留原作业，等待处置。','不伪造维修或生产完成。']], [.24,.46,.30])
    r.p('隔离物品与剩余可用输入分开。第二件是已声明需求，不是自动补产；没有拆解/回收任务，不让投入零件重新出现。复核用预设结果示范，不证明实机可靠性。')
    r.p('本章200秒观察窗，只统计声明目的/工序输出库位接受；若要谈客户履约，还需订单、质量、包装和运输接受条件。有限图表不是现场市场收益。')

    r.page('路径与维护：模块、界面和任务共同更新')
    r.table(['消费者','职责'],[
      ['domain','认可路线、等待位、通道资源、当前设备使用与恢复关联。'],
      ['simulation','唯一货物持有、空驶、互斥、接受、维修、复核与恢复。'],
      ['planner/presentation','两画布覆盖层、详情、共同时间轴与可编辑交接。'],
      ['P1-08/P2-08/P2-09','分别实现维修恢复、路径物流和用户业务面板。']], [.32,.68])
    r.p('九运输与六维护变体已有限复算；全产品28任务仍planned。原41专业方向、九类资产和两画布范围保留，成熟交通/维护机制不单独声明首创。')
    r.p('设备/产线布局、道路资源、库位与维护条件进入同一工程和可重开交付；画面只是这些规则的表现。尚无真实车辆、维修控制或可运行产品。')
