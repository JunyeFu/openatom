"""真实业务对象、规则和自建情景；向量时间图使用手算JSON，不使用AI条带读数。"""
import json,html
from reportlab.lib import colors

LABELS={'assembly':'装配','inspection':'检查','packing':'包装','setup':'换单',
        'transport':'去程','unload':'卸载/下料','return':'返程','load':'上料',
        'auto':'自动','wait_for_worker':'等人员'}
LABELS['wait_for_supply']='等服务'
LABELS['wait_for_output']='等接收'

def gantt(r,jobs,resources,end_s,caption,time_divisor=1000,palette_overrides=None):
    label_width=65; x=r.left+label_width; w=r.width-label_width; top=r.y-20
    palette={'setup':'#866bb2','wait_for_worker':'#b57939','wait_for_supply':'#b57939','wait_for_output':'#b57939','transport':'#427795',
             'unload':'#427795','return':'#8c9da8','inspection':'#4b8a76','packing':'#54869b'}
    if palette_overrides:palette.update(palette_overrides)
    r.c.setFont('CN',8);r.c.setFillColor(colors.HexColor('#586676'))
    for t in range(0,end_s+1,end_s//6):
        px=x+w*t/end_s;r.c.drawCentredString(px,top+7,str(t))
        r.c.setStrokeColor(colors.HexColor('#e0e6e9'));r.c.setLineWidth(.4)
        r.c.line(px,top,px,top-32*len(resources))
    for row,res in enumerate(resources):
        yy=top-row*32-26
        r.c.setFillColor(colors.HexColor('#253443'));r.c.setFont('CN',8.5);r.c.drawString(r.left,yy+8,res)
        for j in jobs:
            if res not in j['resources']:continue
            a=j['start_ms']/time_divisor;b=j['end_ms']/time_divisor
            px=x+w*a/end_s;bw=w*(b-a)/end_s
            r.c.setFillColor(colors.HexColor(palette.get(j['kind'],'#126679')))
            r.c.rect(px,yy,bw,21,fill=1,stroke=0)
            text=LABELS.get(j['kind'],j['kind'])
            if bw>26 or (bw>15 and j['kind'] in ('inspection','packing')):
                if bw<=26:text={'inspection':'检','packing':'包'}[j['kind']]
                r.c.setFillColor(colors.white);r.c.setFont('CN',7);r.c.drawCentredString(px+bw/2,yy+7,text)
    r.y=top-32*len(resources)-15;r.p(caption,'small')
    r.md.append('时间图按以下精确区间绘制（单位以图注为准）：'+str([(j['kind'],j['item'],j['start_ms']/time_divisor,j['end_ms']/time_divisor,j['resources']) for j in jobs]))

